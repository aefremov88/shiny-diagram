const kinds = new Set(["Defining", "Collecting"]);
const documentStates = new Set(["Maintained", "Work-in-progress", "Stale"]);
const implementationStates = new Set(["Aspirational", "Implemented"]);

export function renderMetadata(metadata) {
  validateMetadata(metadata, "generated metadata");
  const lines = [
    `> **Kind:** ${metadata.kind}  `,
    `> **Document state:** ${metadata.documentState}  `,
    `> **Implementation state:** ${metadata.implementationState}  `,
    `> **Last reviewed:** ${metadata.lastReviewed}  `,
    `> **Scope:** ${metadata.scope}  `,
  ];
  if (metadata.kind === "Collecting") {
    lines.push(`> **Generated by:** ${metadata.generatedBy}  `);
  }
  return lines.join("\n");
}

export function parseDocumentMetadata(source, filePath) {
  const lines = source.split(/\r?\n/);
  if (!/^# [^#]/.test(lines[0] ?? "")) {
    throw new Error(`${filePath}: document must start with one level-one title`);
  }
  if (lines[1] !== "") {
    throw new Error(`${filePath}: metadata must follow the title after one blank line`);
  }

  const patterns = [
    [/^> \*\*Kind:\*\* (.+)  $/, "kind"],
    [/^> \*\*Document state:\*\* (.+)  $/, "documentState"],
    [/^> \*\*Implementation state:\*\* (.+)  $/, "implementationState"],
    [/^> \*\*Last reviewed:\*\* (.+)  $/, "lastReviewed"],
    [/^> \*\*Scope:\*\* (.+)  $/, "scope"],
  ];
  const metadata = {};
  for (const [index, [pattern, field]] of patterns.entries()) {
    const match = pattern.exec(lines[index + 2] ?? "");
    if (match === null) {
      throw new Error(`${filePath}: malformed or missing ${field} metadata field`);
    }
    metadata[field] = match[1];
  }
  if (metadata.kind === "Collecting") {
    const match = /^> \*\*Generated by:\*\* (.+)  $/.exec(lines[7] ?? "");
    if (match === null) {
      throw new Error(`${filePath}: malformed or missing generatedBy metadata field`);
    }
    metadata.generatedBy = match[1];
  }
  validateMetadata(metadata, filePath);
  return { title: lines[0].slice(2), ...metadata };
}

export function generationDate() {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

export function generatorLink(modulePath) {
  return `[\`${modulePath}\`](/${modulePath})`;
}

export function generatedWarning(planeName) {
  return `<!-- Auto-generated Never edit by hand. Regenerate with: npm run planes -- ${planeName} -->`;
}

function validateMetadata(metadata, source) {
  if (!kinds.has(metadata.kind)) {
    throw new Error(`${source}: invalid Kind ${JSON.stringify(metadata.kind)}`);
  }
  if (!documentStates.has(metadata.documentState)) {
    throw new Error(`${source}: invalid Document state ${JSON.stringify(metadata.documentState)}`);
  }
  if (!implementationStates.has(metadata.implementationState)) {
    throw new Error(
      `${source}: invalid Implementation state ${JSON.stringify(metadata.implementationState)}`
    );
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(metadata.lastReviewed)) {
    throw new Error(`${source}: invalid Last reviewed ${JSON.stringify(metadata.lastReviewed)}`);
  }
  if (metadata.scope.trim().length === 0) {
    throw new Error(`${source}: Scope must not be empty`);
  }
  if (
    metadata.kind === "Collecting" &&
    !/^\[`[^`]+`\]\(\/scripts\/[^)]+\.mjs\)$/.test(metadata.generatedBy ?? "")
  ) {
    throw new Error(`${source}: Generated by must link to a generator script`);
  }
}
